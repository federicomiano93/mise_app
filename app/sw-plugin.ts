// sw-plugin.ts — writes Mise 2's service worker (`sw.js`, at the root of the build) when Vite has finished.
//
// ⚠️ WHY NOT WORKBOX. The plan said Workbox; it was never a dependency of app/ (8 Nov 2026), and adding it
// means workbox-build and its ~100 packages running at every build for a job of about 300 lines that the
// current app's sw.js already does by hand, tested. The worker is therefore app/sw/worker.js, hand-written
// in the current app's patterns (all-or-nothing precache, copies of unchanged files, a fingerprint per file),
// and this plugin only puts the build's constants above it. No new package.
//
// What it does, in closeBundle (every file is on disk by then, public/ included):
//   1. copies the current app's manifest.json and its two icons from the repository root into the build, so
//      the installed app keeps its identity (same name, same start_url) and Mise 2 can be installed;
//   2. lists every file of the build with the SHA-256 of its bytes (the precache), minus source maps and
//      sw.js itself;
//   3. writes sw.js = the constants + app/sw/worker.js.
// The <head> lines the manifest needs are added to index.html by transformIndexHtml.

import { createHash } from 'node:crypto';
import { copyFileSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Plugin, ResolvedConfig } from 'vite';

const HERE = dirname(fileURLToPath(import.meta.url));
export const WORKER_SOURCE_PATH = join(HERE, 'sw', 'worker.js');
export const LEGACY_ROUTES: Readonly<Record<string, string>> = Object.freeze(Object.fromEntries(
  Object.entries(JSON.parse(readFileSync(join(HERE, 'sw', 'legacy-routes.json'), 'utf8')) as Record<string, string>)
    .filter(([page]) => page !== '//'),
));

// The current app's files that Mise 2 serves too, at the same address (repository root → build root).
export const SHARED_FROM_ROOT = ['manifest.json', 'icons/icon-192.png', 'icons/icon-512.png'] as const;

export interface PrecacheEntry { url: string; rev: string; html?: true }

export function revOf(bytes: Uint8Array): string {
  return createHash('sha256').update(bytes).digest('hex').slice(0, 16);
}

// '/mise_app/' → 'mise2-mise_app--'; '/' → 'mise2-root--'; '/mise2/' → 'mise2-mise2--'. The double hyphen ends it:
// a slug never holds one, so no address's prefix starts another's ('/mise_app/mise2/' is 'mise2-mise_app-mise2--').
export function cachePrefix(base: string): string {
  const slug = base.replace(/^\/+|\/+$/g, '').replace(/[^A-Za-z0-9_]+/g, '-');
  return `mise2-${slug || 'root'}--`;
}

// Beside the current app at /mise2/ (the old preview) Mise 2 must not remove the current app's caches; at
// the site's own address (the switch, the release preview, a local build) it takes them over.
export function takesOver(base: string): boolean {
  return !/\/mise2\/$/.test(base);
}

// What index.html must name to be THIS release's: its entry script and its stylesheets (a release that changed only a
// stylesheet keeps the entry's name), as written in it. Not the modulepreload hints: a proxy that strips them would
// get every copy refused, and that device would never update.
export function pageNeedsOf(indexHtml: string, base: string): string[] {
  const entry = indexHtml.match(/<script[^>]*type="module"[^>]*src="([^"]+)"/)?.[1];
  if (!entry?.startsWith(`${base}assets/`)) throw new Error('sw-plugin: index.html names no module entry script under assets/');
  const styles = [...indexHtml.matchAll(/<link[^>]*rel="stylesheet"[^>]*href="([^"]+)"/g)].map(m => m[1]!)
    .filter(url => url.startsWith(`${base}assets/`));
  return [...new Set([entry, ...styles])].sort();
}

export function composeWorker(opts: { base: string; precache: readonly PrecacheEntry[]; pageNeeds: readonly string[]; source?: string; leftOut?: readonly string[] }): string {
  const source = opts.source ?? readFileSync(WORKER_SOURCE_PATH, 'utf8');
  const prefix = cachePrefix(opts.base);
  const fingerprint = createHash('sha256')
    .update(JSON.stringify(opts.precache)).update(JSON.stringify(opts.pageNeeds)).update(source).digest('hex').slice(0, 12);
  const constants = [
    '// GENERATED by app/sw-plugin.ts from app/sw/worker.js at build time — never edit this file.',
    `const CACHE_NAME = ${JSON.stringify(prefix + fingerprint)};`,
    `const CACHE_PREFIX = ${JSON.stringify(prefix)};`,
    `const PRECACHE = ${JSON.stringify(opts.precache)};`,
    `const PAGE_NEEDS = ${JSON.stringify(opts.pageNeeds)};`,
    `const TAKE_OVER = ${JSON.stringify(takesOver(opts.base))};`,
    `const LEGACY_ROUTES = ${JSON.stringify(LEGACY_ROUTES)};`,
    '// Built, deliberately NOT precached (never loaded: sw-plugin.ts, NEVER_LOADED_PACKAGES). Read by sw/verify-build.mjs only.',
    `const LEFT_OUT = ${JSON.stringify([...(opts.leftOut ?? [])].sort())};`,
    '',
  ].join('\n');
  return constants + source;
}

function filesUnder(dir: string, out: string[] = []): string[] {
  for (const name of readdirSync(dir)) {
    const full = join(dir, name);
    if (statSync(full).isDirectory()) filesUnder(full, out);
    else out.push(full);
  }
  return out;
}

// ⚠️ jsPDF's OPTIONAL dependencies are emitted as chunks nothing ever loads (its html() and svg paths, which the recipe
// export does not use: docs/architecture.md, recipe export). Precached, every phone would download ~380 KB for nothing,
// so a chunk made ONLY of these packages is left out — by the modules it holds, never by a file-name glob.
export const NEVER_LOADED_PACKAGES = [
  'html2canvas', 'canvg', 'dompurify', 'core-js', 'raf', 'rgbcolor', 'stackblur-canvas', 'svg-pathdata',
  'performance-now', 'regenerator-runtime', '@babel/runtime',
] as const;
const NEVER_LOADED = new RegExp(`[\\\\/]node_modules[\\\\/](${NEVER_LOADED_PACKAGES.map(p => p.replace('/', '[\\\\/]')).join('|')})[\\\\/]`);

export function neverLoadedChunk(moduleIds: readonly string[]): boolean {
  return moduleIds.length > 0 && moduleIds.every(id => NEVER_LOADED.test(id));
}

// What is NOT precached: the worker itself, source maps, Vite's own manifest folder, the never-loaded chunks above,
// and any page other than index.html (none today).
export function precached(path: string, leftOut: ReadonlySet<string> = new Set()): boolean {
  if (path === 'sw.js' || path.endsWith('.map') || path.startsWith('.vite/') || leftOut.has(path)) return false;
  if (path.endsWith('.html') && path !== 'index.html') return false;
  return true;
}

export function miseServiceWorker(repoRoot = join(HERE, '..')): Plugin {
  let config: ResolvedConfig;
  const leftOut = new Set<string>();
  return {
    name: 'mise2-service-worker',
    apply: 'build',
    configResolved(resolved) { config = resolved; },
    transformIndexHtml: {
      order: 'post',
      handler: () => [
        { tag: 'link', attrs: { rel: 'manifest', href: `${config.base}manifest.json` }, injectTo: 'head' },
        { tag: 'link', attrs: { rel: 'apple-touch-icon', href: `${config.base}icons/icon-192.png` }, injectTo: 'head' },
        { tag: 'meta', attrs: { name: 'theme-color', content: '#2D5016' }, injectTo: 'head' },
      ],
    },
    generateBundle(_options, bundle) {
      for (const file of Object.values(bundle)) {
        if (file.type === 'chunk' && neverLoadedChunk(Object.keys(file.modules))) leftOut.add(file.fileName);
      }
    },
    closeBundle() {
      const outDir = resolve(config.root, config.build.outDir);
      for (const file of SHARED_FROM_ROOT) {
        mkdirSync(dirname(join(outDir, file)), { recursive: true });
        copyFileSync(join(repoRoot, file), join(outDir, file));
      }
      const precache: PrecacheEntry[] = filesUnder(outDir)
        .map(full => relative(outDir, full).split(sep).join('/'))
        .filter(path => precached(path, leftOut))
        .sort()
        .map(url => {
          const rev = revOf(readFileSync(join(outDir, url)));
          return url === 'index.html' ? { url, rev, html: true as const } : { url, rev };
        });
      const pageNeeds = pageNeedsOf(readFileSync(join(outDir, 'index.html'), 'utf8'), config.base);
      writeFileSync(join(outDir, 'sw.js'), composeWorker({ base: config.base, precache, pageNeeds, leftOut: [...leftOut] }));
    },
  };
}
