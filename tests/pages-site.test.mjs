// The site GitHub Pages serves after the switch (scripts/build-pages-site.mjs, .github/workflows/pages.yml), EXECUTED on
// an invented Mise 2 build and this checkout's own current-app files, then checked through scripts/verify-live-site.mjs
// served from a local HTTP server — the same check the switch hour runs against the live site.
//
// What must hold, because people already hold links to it:
//   - Mise 2 is the site's index.html and its sw.js (the current app's address: that is the switch);
//   - order.html (clients' ordering links) and reset-password.html (the password email) are the committed files,
//     byte for byte, with every file they load;
//   - every other page of the current app is a stub that opens its Mise 2 screen;
//   - nothing internal is published, and a Mise 2 file never silently replaces a current-app file.

import { test } from 'node:test';
import assert from 'node:assert/strict';
import { createServer } from 'node:http';
import { mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync, existsSync, createReadStream, statSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, dirname, extname } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildSite, legacyRoutes } from '../scripts/build-pages-site.mjs';
import { verifySite } from '../scripts/verify-live-site.mjs';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');

// A Mise 2 build as app/sw-plugin.ts leaves it: index.html, a generated sw.js listing what it precaches, assets.
function fakeMise2(dir, extra = {}) {
  const files = {
    'index.html': '<!doctype html><meta charset="utf-8"><script>document.write(\'<meta http-equiv="Content-Security-Policy" content="default-src \\\'self\\\'">\')</script><script type="module" src="/mise_app/assets/index-abc.js"></script><link rel="stylesheet" href="/mise_app/assets/index-abc.css">',
    'assets/index-abc.js': 'console.log(1)',
    'assets/index-abc.css': 'body{}',
    'favicon.svg': '<svg/>',
    ...extra,
  };
  for (const [file, body] of Object.entries(files)) {
    mkdirSync(dirname(join(dir, file)), { recursive: true });
    writeFileSync(join(dir, file), body);
  }
  for (const file of ['manifest.json', 'icons/icon-192.png', 'icons/icon-512.png']) {
    mkdirSync(dirname(join(dir, file)), { recursive: true });
    writeFileSync(join(dir, file), readFileSync(join(ROOT, file)));
  }
  const precache = Object.keys(files).concat(['manifest.json', 'icons/icon-192.png', 'icons/icon-512.png']).map(url => ({ url, rev: 'x' }));
  writeFileSync(join(dir, 'sw.js'), `// GENERATED by app/sw-plugin.ts from app/sw/worker.js at build time — never edit this file.
const CACHE_NAME = "mise2-mise_app--000000000000";
const PRECACHE = ${JSON.stringify(precache)};
const PAGE_NEEDS = ["/mise_app/assets/index-abc.css","/mise_app/assets/index-abc.js"];
`);
}

function serve(siteDir) {
  const types = { '.html': 'text/html', '.js': 'text/javascript', '.css': 'text/css', '.json': 'application/json' };
  const server = createServer((req, res) => {
    const path = decodeURIComponent(new URL(req.url, 'http://x').pathname);
    if (!path.startsWith('/mise_app/')) { res.writeHead(404); res.end(); return; }
    const file = join(siteDir, path.slice('/mise_app/'.length) || 'index.html');
    if (!file.startsWith(siteDir) || !existsSync(file) || statSync(file).isDirectory()) { res.writeHead(404); res.end(); return; }
    res.writeHead(200, { 'content-type': types[extname(file)] ?? 'application/octet-stream' });
    createReadStream(file).pipe(res);
  });
  return new Promise(done => server.listen(0, '127.0.0.1', () => done(server)));
}

test('the site after the switch: Mise 2 at the root, the clients\' and password pages whole, stubs, nothing internal', async () => {
  const tmp = mkdtempSync(join(tmpdir(), 'pages-site-'));
  try {
    const dist = join(tmp, 'dist');
    fakeMise2(dist);
    const site = join(tmp, '_site');
    const { files, problems } = buildSite(site, dist);
    assert.deepEqual(problems, []);

    assert.equal(readFileSync(join(site, 'index.html'), 'utf8'), readFileSync(join(dist, 'index.html'), 'utf8'), 'index.html is Mise 2');
    assert.match(readFileSync(join(site, 'sw.js'), 'utf8'), /GENERATED by app\/sw-plugin\.ts/, 'sw.js is Mise 2\'s worker');
    for (const page of ['order.html', 'reset-password.html', 'install-guide.html', 'home.html']) {
      assert.ok(readFileSync(join(site, page)).equals(readFileSync(join(ROOT, page))), `${page} is the committed file`);
    }
    for (const [page, route] of Object.entries(legacyRoutes())) {
      if (page === 'home.html') continue;
      assert.match(readFileSync(join(site, page), 'utf8'), new RegExp(`url=\\./${route ? `#${route.replace('/', '\\/')}` : ''}"`), `${page} → ${route}`);
    }
    for (const internal of ['firestore.rules', 'firebase.json', 'package.json', 'functions', 'app', 'shared', 'tests', 'scripts', 'docs', '.github', '.claude', 'CLAUDE.md', 'README.md']) {
      assert.ok(!files.some(f => f === internal || f.startsWith(`${internal}/`)), `${internal} must not be published`);
    }
    assert.ok(!files.some(f => f.endsWith('.map') && f.startsWith('assets/')), 'no Mise 2 source map');

    // The check the switch hour runs against the live site, here against this one.
    const server = await serve(site);
    try {
      const result = await verifySite(`http://127.0.0.1:${server.address().port}/mise_app/`);
      assert.deepEqual(result.problems, []);
      assert.ok(result.keptPagesFiles > 10, `the kept pages' files were followed (${result.keptPagesFiles})`);
    } finally { server.close(); }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
});

test('a Mise 2 file never silently replaces a current-app file of the same name', () => {
  const tmp = mkdtempSync(join(tmpdir(), 'pages-site-'));
  try {
    const dist = join(tmp, 'dist');
    fakeMise2(dist, { 'order.html': '<p>not the clients\' page</p>' });
    const { problems } = buildSite(join(tmp, '_site'), dist);
    assert.deepEqual(problems, ['order.html: both apps have a file of this name']);
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
});

test('the live check sees a missing file and a site that is still the current app', async () => {
  const tmp = mkdtempSync(join(tmpdir(), 'pages-site-'));
  try {
    const dist = join(tmp, 'dist');
    fakeMise2(dist);
    const site = join(tmp, '_site');
    buildSite(site, dist);
    rmSync(join(site, 'dist/order.js'));
    writeFileSync(join(site, 'sw.js'), readFileSync(join(ROOT, 'sw.js')));
    const server = await serve(site);
    try {
      const { problems } = await verifySite(`http://127.0.0.1:${server.address().port}/mise_app/`);
      assert.ok(problems.some(p => p.includes('dist/order.js')), problems.join('\n'));
      assert.ok(problems.some(p => p.includes('not Mise 2')), problems.join('\n'));
    } finally { server.close(); }
  } finally {
    rmSync(tmp, { recursive: true, force: true });
  }
});

test('pages.yml: deploys only from main, builds where no credential exists, and is wired to these two scripts', () => {
  const wf = readFileSync(join(ROOT, '.github/workflows/pages.yml'), 'utf8');
  const build = wf.slice(wf.indexOf('\n  pages-site:'), wf.indexOf('\n  deploy:'));
  const deploy = wf.slice(wf.indexOf('\n  deploy:'));
  assert.match(build, /permissions:\n {6}contents: read\n/);
  assert.doesNotMatch(build, /id-token|pages: write/);
  assert.match(build, /npm run build -- --base=\/mise_app\//);
  assert.match(build, /node sw\/verify-build\.mjs dist/);
  assert.match(build, /set -o pipefail\n\s+node scripts\/build-pages-site\.mjs _site app\/dist/);
  assert.match(deploy, /if: github\.ref == 'refs\/heads\/main' && github\.event_name != 'pull_request'/);
  assert.doesNotMatch(deploy, /checkout|npm |run:/, 'the deploy job runs nothing but GitHub\'s deploy action');
  assert.match(wf, /push:\n {4}branches: \[main\]/);
});
